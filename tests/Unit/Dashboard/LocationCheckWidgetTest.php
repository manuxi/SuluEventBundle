<?php

declare(strict_types=1);

namespace Manuxi\SuluEventBundle\Tests\Unit\Dashboard;

use Manuxi\SuluEventBundle\Dashboard\EventDashboardReader;
use Manuxi\SuluEventBundle\Dashboard\LocationCheckWidget;
use Manuxi\SuluEventBundle\Entity\Location;

class LocationCheckWidgetTest extends DashboardTestCase
{
    /**
     * @param list<Location> $locations
     */
    private function widget(array $locations): LocationCheckWidget
    {
        $reader = $this->createMock(EventDashboardReader::class);
        $reader->method('locations')->willReturn($locations);

        return new LocationCheckWidget($reader);
    }

    /**
     * @param array<string, mixed>|null $map
     */
    private function location(?string $street, ?string $postalCode, ?string $city, ?array $map, string $name = 'Hall'): Location
    {
        $location = (new Location())
            ->setName($name)
            ->setStreet($street)
            ->setPostalCode($postalCode)
            ->setCity($city)
            ->setLocation($map);

        // the id is generated by the database
        (new \ReflectionProperty(Location::class, 'id'))->setValue($location, 7);

        return $location;
    }

    public function testDescriptionOfTheTile(): void
    {
        $widget = $this->widget([]);

        $this->assertSame('sulu_event_locations', $widget->getKey());
        $this->assertSame('list', $widget->getType());
        $this->assertSame('side', $widget->getColumn());
        $this->assertSame('sulu.events.events', $widget->getSecurityContext());
    }

    public function testCompleteLocationsAreNotListed(): void
    {
        $data = $this->widget([
            $this->location('Main street', '10115', 'Berlin', ['lat' => 52.52, 'long' => 13.4]),
        ])->getData('de');

        $this->assertSame([], $data['rows']);
        $this->assertSame('sulu_event_dashboard.locations_ok', $data['empty']);
    }

    public function testListsWhatIsMissingAndLinksToTheForm(): void
    {
        $data = $this->widget([
            $this->location('Main street', '10115', 'Berlin', null, 'No map'),
            $this->location(null, ' ', null, ['lat' => 52.5, 'long' => 13.4], 'No address'),
        ])->getData('en');

        $this->assertCount(2, $data['rows']);

        $this->assertSame('No map', $data['rows'][0]['title']);
        $this->assertSame('sulu_event_dashboard.missing_coordinates', $data['rows'][0]['meta']);
        $this->assertSame(
            ['view' => 'sulu_event.location.edit_form', 'attributes' => ['id' => 7]],
            $data['rows'][0]['link']
        );

        $this->assertSame(
            ['key' => 'sulu_event_dashboard.missing_several', 'parameters' => ['count' => 3]],
            $data['rows'][1]['meta']
        );
    }

    public function testEmptyOrZeroCoordinatesCountAsMissing(): void
    {
        $data = $this->widget([
            $this->location('a', '1', 'b', ['lat' => 0, 'long' => 0], 'zero'),
            $this->location('a', '1', 'b', ['lat' => '', 'long' => null], 'empty'),
            $this->location('a', '1', 'b', ['lat' => '52.5', 'long' => '13.4'], 'text values are fine'),
            $this->location('a', '1', 'b', ['lat' => 0, 'long' => 13.4], 'on the meridian'),
        ])->getData('en');

        $this->assertSame(['zero', 'empty'], array_column($data['rows'], 'title'));
    }
}
